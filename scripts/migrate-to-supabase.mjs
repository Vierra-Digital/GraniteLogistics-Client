// Transform a Granite workspace export into Supabase-ready SQL and photo files.
//
//   node scripts/migrate-to-supabase.mjs <workspace.json> [outDir]
//
// Input is whatever `Settings -> Data Management -> Export full backup (JSON)` produces, or
// the body of GET /api/state. Output is a directory you can apply by hand:
//
//   01-packages.sql     rows for packages / package_events / manifests / load_units
//   02-accounts.csv     emails, names and roles for the people who need accounts
//   photos/             condition photos as real image files, named by their storage path
//   MIGRATION.md        what to do with all of it, and what it cannot do for you
//
// It touches no network and no live system. Run it, read the output, then decide.
//
// Deliberately not automated end-to-end: applying it needs a Supabase project, and the
// schema it targets (supabase/schema-relational.sql) has never been run against a real
// Postgres, so the first application should be somebody watching it.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

// Only read argv when run directly. Imported -- by a test, say -- process.argv[2] is the
// test file, and this would try to JSON.parse it at import time.
import { fileURLToPath } from "node:url";
const RUN_DIRECTLY = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
const [, , inPath, outDir = "supabase/migration-out"] = RUN_DIRECTLY ? process.argv : [];
if (RUN_DIRECTLY && !inPath) {
  console.error("usage: node scripts/migrate-to-supabase.mjs <workspace.json> [outDir]");
  process.exit(2);
}

const TENANT = process.env.GL_TENANT || "default";

// ---- SQL literals -----------------------------------------------------------------
// Everything reaching these came out of a JSON export, so it is data, not SQL. Quoted
// rather than interpolated, and jsonb goes through the same escaping as any other string.
const lit = (v) => {
  if (v === null || v === undefined || v === "") return "null";
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const jsonLit = (o) => (o && Object.keys(o).length ? lit(JSON.stringify(o)) + "::jsonb" : "'{}'::jsonb");
const tsLit = (ms) => (Number.isFinite(ms) ? lit(new Date(ms).toISOString()) : "null");

// ---- photos -----------------------------------------------------------------------
// Stored today as data URLs inside the workspace record, which is the whole reason the
// record hits its ceiling. They come out here as files plus the storage path that the
// packages row will point at.
function extractPhoto(dataUrl, tenant, pkgId, kind, outRoot) {
  if (typeof dataUrl !== "string" || !dataUrl.startsWith("data:")) return null;
  const m = /^data:([^;]+);base64,(.*)$/s.exec(dataUrl);
  if (!m) return null;
  const ext = { "image/webp": "webp", "image/jpeg": "jpg", "image/png": "png" }[m[1]] || "bin";
  const rel = `${tenant}/${pkgId}/${kind}.${ext}`;
  const abs = join(outRoot, "photos", rel);
  mkdirSync(join(abs, ".."), { recursive: true });
  writeFileSync(abs, Buffer.from(m[2], "base64"));
  return { path: rel, bytes: Buffer.from(m[2], "base64").length };
}

// ---- transform --------------------------------------------------------------------
export function transform(ws, outRoot, tenant = TENANT) {
  const packages = Array.isArray(ws.packages) ? ws.packages : [];
  const manifests = Array.isArray(ws.manifests) ? ws.manifests : [];
  const loadUnits = Array.isArray(ws.loadUnits) ? ws.loadUnits : [];

  const sql = [];
  const photos = [];
  const accounts = new Map();
  let events = 0;

  sql.push("-- generated by scripts/migrate-to-supabase.mjs");
  sql.push("-- targets supabase/schema-relational.sql");
  sql.push("begin;");
  sql.push(`insert into public.tenants (slug) values (${lit(tenant)}) on conflict do nothing;`);

  for (const p of packages) {
    if (!p || !p.id) continue;

    const pickup = extractPhoto(p.photos && p.photos.pickup, tenant, p.id, "pickup", outRoot);
    const delivery = extractPhoto(p.photos && p.photos.delivery, tenant, p.id, "delivery", outRoot);
    if (pickup) photos.push(pickup);
    if (delivery) photos.push(delivery);

    const cust = p.customer || {};
    // A customer row is only implied by an order carrying an address. Recorded so somebody
    // can decide who actually needs an account rather than creating one per parcel.
    if (p.customerEmail) {
      accounts.set(String(p.customerEmail).toLowerCase(),
        { email: String(p.customerEmail).toLowerCase(), name: cust.name || "", role: "Customer" });
    }

    sql.push(
      "insert into public.packages (tenant, id, status, source, order_ref, barcode, carrier, lane, " +
      "batch_id, tracking, item, customer, customer_email, photo_pickup, photo_delivery, " +
      "load_unit, sort_zone, presort_lane, promised_at, exception, return_state, created_at) values (" +
      [
        lit(tenant), lit(p.id), lit(p.status), lit(p.source), lit(p.orderRef), lit(p.barcode),
        lit(p.carrier), lit(p.lane), lit(p.batchId), lit(p.tracking),
        jsonLit(p.item), jsonLit(cust), lit(p.customerEmail),
        pickup ? lit(pickup.path) : "null",
        delivery ? lit(delivery.path) : "null",
        lit(p.loadUnit), lit(p.sortZone), lit(p.presortLane),
        tsLit(p.promisedTs), p.exception ? jsonLit(p.exception) : "null",
        p.return ? jsonLit(p.return) : "null",
        // The first history entry is the closest thing to a creation time.
        tsLit((p.history && p.history[0] && p.history[0].ts) || Date.now()),
      ].join(", ") + ") on conflict (tenant, id) do nothing;"
    );

    for (const h of (Array.isArray(p.history) ? p.history : [])) {
      if (!h || !h.stage) continue;
      events++;
      sql.push(
        "insert into public.package_events (package_uid, stage, note, at) select uid, " +
        [lit(h.stage), lit(h.note), tsLit(h.ts)].join(", ") +
        ` from public.packages where tenant = ${lit(tenant)} and id = ${lit(p.id)};`
      );
    }
  }

  for (const m of manifests) {
    if (!m || !m.id) continue;
    sql.push(
      "insert into public.manifests (tenant, id, carrier, lane, transmitted, created_at) values (" +
      [lit(tenant), lit(m.id), lit(m.carrier), lit(m.lane), m.transmitted ? "true" : "false", tsLit(m.ts)].join(", ") +
      ") on conflict (tenant, id) do nothing;"
    );
  }
  for (const l of loadUnits) {
    if (!l || !l.id) continue;
    sql.push(
      "insert into public.load_units (tenant, id, zone, lane, weight_lb, created_at) values (" +
      [lit(tenant), lit(l.id), lit(l.zone), lit(l.lane),
       Number.isFinite(l.weightLb) ? String(l.weightLb) : "null", tsLit(l.ts)].join(", ") +
      ") on conflict (tenant, id) do nothing;"
    );
  }

  // The Activity Log, and the settings worth keeping. `cloud` carries an api key and theme
  // and role are per-device, so they are dropped rather than migrated -- same rule the live
  // data layer applies in settingsForStorage.
  let activity = 0;
  for (const e of (Array.isArray(ws.events) ? ws.events : [])) {
    if (!e || !e.ts) continue;
    activity++;
    sql.push(
      "insert into public.activity_events (tenant, package_id, kind, who, note, at) values (" +
      [lit(tenant), lit(e.pkgId), lit(e.kind), lit(e.who), lit(e.note), tsLit(e.ts)].join(", ") +
      ") on conflict do nothing;"
    );
  }
  const settings = { ...(ws.settings || {}) };
  for (const k of ["cloud", "theme", "role", "roleChosen"]) delete settings[k];
  sql.push(
    "insert into public.workspace_settings (tenant, settings) values (" +
    [lit(tenant), jsonLit(settings)].join(", ") +
    ") on conflict (tenant) do update set settings = excluded.settings;"
  );

  sql.push("commit;");

  return {
    sql: sql.join("\n") + "\n",
    accounts: [...accounts.values()],
    counts: {
      packages: packages.length, events, manifests: manifests.length,
      loadUnits: loadUnits.length, photos: photos.length, activity,
      photoBytes: photos.reduce((a, p) => a + p.bytes, 0),
      // The number that motivates the whole exercise.
      recordChars: JSON.stringify(ws).length,
    },
  };
}

// ---- run --------------------------------------------------------------------------
if (inPath) {
  const ws = JSON.parse(readFileSync(inPath, "utf8"));
  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  const out = transform(ws, outDir);

  writeFileSync(join(outDir, "01-packages.sql"), out.sql);
  writeFileSync(join(outDir, "02-accounts.csv"),
    "email,name,role\n" + out.accounts.map((a) => `${a.email},"${(a.name || "").replace(/"/g, '""')}",${a.role}\n`).join(""));

  const c = out.counts;
  const pct = Math.round(c.photoBytes * 1.37 / Math.max(1, c.recordChars) * 100);
  writeFileSync(join(outDir, "MIGRATION.md"), [
    "# Migration output",
    "",
    `Source: \`${inPath}\``,
    "",
    "| | |",
    "| --- | --- |",
    `| packages | ${c.packages} |`,
    `| history events | ${c.events} |`,
    `| manifests | ${c.manifests} |`,
    `| load units | ${c.loadUnits} |`,
    `| condition photos | ${c.photos} (${Math.round(c.photoBytes / 1024)} KB as files) |`,
    `| workspace record | ${c.recordChars.toLocaleString()} characters |`,
    "",
    `Photos are roughly **${pct}%** of that record as base64. Moving them to Storage is the`,
    "single biggest reduction available, and it is the one step that does not touch auth.",
    "",
    "## To apply",
    "",
    "1. Run `supabase/schema-relational.sql` in the SQL editor. It has never been applied to a",
    "   real Postgres, so read it first and watch the first run.",
    "2. Create the `condition-photos` bucket (private) and upload `photos/` preserving paths.",
    "3. Run `01-packages.sql`.",
    "4. Verify RLS actually denies what it should. A policy that returns zero rows looks",
    "   identical to an empty table, so test it as a customer, a Viewer and an Admin before",
    "   trusting it.",
    "",
    "## What this cannot do",
    "",
    "**Passwords do not migrate.** Accounts here are hashed with scrypt",
    "(`_auth.mjs` hashPw); Supabase Auth stores bcrypt in `auth.users.encrypted_password` and",
    "cannot import a foreign hash. Every account in `02-accounts.csv` will need to set a new",
    "password.",
    "",
    "That matters for sequencing: with `GL_BREVO_KEY` unset there is no self-service reset, so",
    "the only route is Team & Roles -> Reset password, one account at a time, performed by an",
    "admin who can still sign in. **Configure email before converting auth**, or the",
    "conversion strands every account including possibly your own.",
    "",
  ].join("\n"));

  console.log("wrote " + outDir + "/");
  console.log("  packages %d, events %d, manifests %d, load units %d, photos %d (%d KB)",
    c.packages, c.events, c.manifests, c.loadUnits, c.photos, Math.round(c.photoBytes / 1024));
  console.log("  workspace record: %s characters, photos ~%d%% of it",
    c.recordChars.toLocaleString(), pct);
}
